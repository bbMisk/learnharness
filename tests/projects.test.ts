import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { after, it } from 'node:test';
import { createFauxCore, fauxAssistantMessage } from '@earendil-works/pi-ai';
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'lh-projects-test-'));
process.env.LH_DATA_DIR = root;
process.env.LH_AUTH_FILE = path.join(root, 'auth.json');
const { projectStore, projectInstructions } = await import('../src/server/projects.ts');
const { createProjectStore } = await import('../src/store/projects.ts');
const { uploadStore } = await import('../src/store/uploads.ts');
const { chatStore, setChatOrganization } = await import('../src/store/chats.ts');
const projects = await import('../app/api/projects/route.ts');
const project = await import('../app/api/projects/[id]/route.ts');
const chats = await import('../app/api/chats/route.ts');
const chatRoute = await import('../app/api/chats/[id]/route.ts');
const { createTeacherAgent } = await import('../src/agent/teacher-agent.ts');
after(() => fs.rmSync(root, { recursive: true, force: true }));
const request = (body: object) => new Request('http://test/api', { method: 'POST', body: JSON.stringify(body) });
it('persists project files/instructions, assigns chats, and injects fresh shared context into the actual agent', async () => {
    const response = await projects.POST(request({ name: 'Quant study' }));
    assert.equal(response.status, 201);
    const p = await response.json();
    const file = await uploadStore.save('shared notes.md', new Blob(['A shared course note.']).stream());
    const saved = await project.PUT(request({ instructions: 'Use course notation. PROJECT_SENTINEL', expected:{instructions:''}, addFileIds: [file.id] }), { params: Promise.resolve({ id: p.id }) });
    assert.equal(saved.status, 200);
    const persisted = createProjectStore(path.join(root, 'projects')).get(p.id)!;
    assert.deepEqual(persisted.fileIds, [file.id]);
    assert.match(persisted.instructions, /PROJECT_SENTINEL/);
    const created = await chats.POST(request({ title: 'Study the notes', projectId: p.id }));
    assert.equal(created.status, 200);
    const c = await created.json();
    assert.equal(chatStore.getChat(c.id)!.projectId, p.id);
    const before = chatStore.getChat(c.id)!;
    setChatOrganization(c.id, { pinned: true });
    assert.equal(chatStore.getChat(c.id)!.updatedAt, before.updatedAt);
    assert.equal(chatStore.listChats()[0]!.pinned, true);
    chatStore.saveMessages(c.id, [{ id: 'u', role: 'user', content: 'Keep this lesson.', timestamp: 1 }]);
    assert.equal(chatStore.getChat(c.id)!.projectId, p.id);
    assert.equal(chatStore.getChat(c.id)!.pinned, true);
    let observed = false;
    const faux = createFauxCore({});
    faux.setResponses([(context) => { const system = JSON.stringify(context.messages.filter(m => m.role === "system")); assert.match(system, /PROJECT_SENTINEL/); assert.ok(system.includes(file.path)); observed = true; return fauxAssistantMessage('I can use the project.'); }]);
    const agent = createTeacherAgent(undefined, { engine: { model: faux.getModel(), streamFn: faux.streamSimple }, tools: {}, projectContext: await projectInstructions(p.id) });
    await agent.prompt('What project context is available?');
    assert.ok(observed);
    projectStore.update(p.id, { instructions: 'UPDATED_SENTINEL' });
    assert.match(await projectInstructions(p.id), /UPDATED_SENTINEL/);
    assert.equal((await chats.POST(request({ title: 'bad', projectId: 'project_missing' }))).status, 400);
    assert.equal((await chatRoute.PUT(request({ projectId: 'project_missing' }), { params: Promise.resolve({ id: c.id }) })).status, 400);
    assert.equal((await project.PUT(request({ addFileIds: ['not-a-file'] }), { params: Promise.resolve({ id: p.id }) })).status, 400);
    await chatRoute.PUT(request({ pinned: false, projectId: null }), { params: Promise.resolve({ id: c.id }) });
    assert.equal(chatStore.getChat(c.id)!.projectId, undefined);
    assert.equal(chatStore.getChat(c.id)!.messages.length, 1);
});

it('keeps concurrent file changes and rejects conflicting text while allowing independent fields', async () => {
 const p = projectStore.create('Concurrency test');
 const a = await uploadStore.save('a.txt', new Blob(['A']).stream());
 const b = await uploadStore.save('b.txt', new Blob(['B']).stream());
 const context = {params:Promise.resolve({id:p.id})};
 const put = (body:object) => project.PUT(request(body), context);
 assert.equal((await put({addFileIds:[a.id]})).status, 200);
 const before = projectStore.get(p.id)!;
 const together = await Promise.all([put({addFileIds:[b.id]}), put({removeFileIds:[a.id]})]);
 assert.ok(together.every(r => r.status === 200));
 assert.deepEqual(projectStore.get(p.id)!.fileIds, [b.id], 'removing A must retain B added on another client');
 assert.ok(projectStore.get(p.id)!.updatedAt > before.updatedAt);
 assert.equal((await put({instructions:'old client without a baseline'})).status, 400);
 assert.equal((await put({instructions:'Client A', expected:{instructions:''}})).status, 200);
 const stale = await put({instructions:'Client B', expected:{instructions:''}});
 assert.equal(stale.status, 409);
 assert.deepEqual((await stale.json()).conflicts, ['instructions']);
 assert.equal(projectStore.get(p.id)!.instructions, 'Client A');
 assert.equal((await put({name:'Independent name', expected:{name:p.name}})).status, 200, 'an instructions edit must not reject an independent rename');
 assert.equal((await put({instructions:'Client B', expected:{instructions:'Client A'}})).status, 200, 'explicitly rebased edits can be saved');
 assert.equal((await put({fileIds:[]})).status, 400, 'stale whole-list replacement is not a removal operation');
 const listing = await (await projects.GET()).json();
 assert.ok(listing.projects.every((p:object) => Object.keys(p).sort().join(',') === 'id,name'));
});

it('keeps projects editable and chats usable when a shared upload disappears', async () => {
 const p = projectStore.create('Recovery project');
 const missing = await uploadStore.save('missing.txt', new Blob(['Missing notes.']).stream());
 const available = await uploadStore.save('available.txt', new Blob(['Available notes.']).stream());
 projectStore.update(p.id, { fileIds: [missing.id, available.id], instructions: 'Keep course notation.' });
 fs.unlinkSync(missing.path);
 const context = {params:Promise.resolve({id:p.id})};
 const loaded = await project.GET(new Request('http://test/api'), context);
 assert.equal(loaded.status, 200);
 const view = await loaded.json();
 assert.deepEqual(view.missingFileIds, [missing.id]);
 assert.deepEqual(view.files.map((f:{id:string}) => f.id), [available.id]);
 const instructions = await projectInstructions(p.id);
 assert.match(instructions, /unavailable/);
 assert.match(instructions, /contents were not supplied/);
 assert.ok(instructions.includes(available.path));
 assert.ok(!instructions.includes(missing.path));
 const edited = await project.PUT(request({ instructions: 'Updated instructions.', expected:{instructions:'Keep course notation.'} }), context);
 assert.equal(edited.status, 200, 'saving must not commit and then report a projection failure');
 assert.equal((await edited.json()).instructions, 'Updated instructions.');
 const removed = await project.PUT(request({removeFileIds:[missing.id]}), context);
 assert.equal(removed.status, 200);
 assert.deepEqual((await removed.json()).fileIds, [available.id]);
 assert.deepEqual(projectStore.get(p.id)!.fileIds, [available.id]);
 assert.doesNotMatch(await projectInstructions(p.id), /unavailable/);
});
